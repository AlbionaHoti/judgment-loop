"""Write notebook/Modelfile from judgment.config.json.

The Modelfile's SYSTEM prompt must be the one the model was trained and
tested with, so it is generated, not hand-edited. Change the prompt in
judgment.config.json, then:

  python3 notebook/render_modelfile.py

The TEMPLATE below is ChatML, which is what Qwen models use. If you change
the base model family, change the template to match that family's chat
format - a wrong template silently degrades answers.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from jl import config  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Modelfile")

CHATML = '''TEMPLATE """{{ if .System }}<|im_start|>system
{{ .System }}<|im_end|>
{{ end }}{{ if .Prompt }}<|im_start|>user
{{ .Prompt }}<|im_end|>
{{ end }}<|im_start|>assistant
{{ .Response }}<|im_end|>
"""

PARAMETER stop <|im_start|>
PARAMETER stop <|im_end|>'''


def render(cfg):
    if '"""' in cfg["system_prompt"]:
        raise SystemExit('system_prompt may not contain """')
    return (
        "# Generated by notebook/render_modelfile.py from judgment.config.json.\n"
        "# Do not edit by hand.\n"
        f"FROM ./{cfg['gguf_file']}\n\n"
        f"{CHATML}\n"
        f"PARAMETER temperature {cfg['deploy']['temperature']}\n\n"
        f'SYSTEM """{cfg["system_prompt"]}"""\n'
    )


if __name__ == "__main__":
    text = render(config.load())
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")
